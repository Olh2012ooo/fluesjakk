def selfplay_loss(logits: torch.Tensor, value: torch.Tensor, pi: torch.Tensor, z: torch.Tensor,
                  legal_mask: torch.Tensor | None = None, value_weight: float = 1.0
                  ) -> tuple[torch.Tensor, dict[str, torch.Tensor]]:
    """``-(pi · log_softmax(logits)) + value_weight · mse(value, z)`` with illegal moves masked out.

    Returns ``(loss, metrics)``; metrics are detached device tensors (``loss, policy_loss, value_loss,
    top1, top3`` where top-k compares the network's argmax with the search's most visited move).
    """
    loss, metrics, _ = _row_losses(logits, value, pi, z, legal_mask, value_weight)
    return loss, metrics


def _row_losses(logits: torch.Tensor, value: torch.Tensor, pi: torch.Tensor, z: torch.Tensor,
                legal_mask: torch.Tensor | None, value_weight: float
                ) -> tuple[torch.Tensor, dict[str, torch.Tensor], dict[str, torch.Tensor]]:
    """The loss of :func:`selfplay_loss` plus the detached per-row terms (``policy``, ``value``, ``hit1``, ``hit3``)."""
    logp = masked_policy_log_softmax(logits, legal_mask)
    if legal_mask is not None:
        logp = logp.masked_fill(~legal_mask.to(torch.bool), 0.0)   # pi is 0 there: avoid 0 * -inf
    row_policy = -(pi.float() * logp).sum(dim=-1)
    v = value.float().view(-1)
    row_value = (v - z.float().view(-1)) ** 2
    policy_loss = row_policy.mean()
    value_loss = row_value.mean()
    loss = policy_loss + value_weight * value_loss
    with torch.no_grad():
        target = pi.argmax(dim=-1)
        top3 = logp.masked_fill(~legal_mask.to(torch.bool), float("-inf")).topk(3, dim=-1).indices if legal_mask is not None else logp.topk(3, dim=-1).indices
        hit = top3 == target.unsqueeze(1)
        metrics = {"loss": loss.detach(), "policy_loss": policy_loss.detach(), "value_loss": value_loss.detach(),
                   "top1": hit[:, 0].float().mean(), "top3": hit.any(dim=1).float().mean()}
        rows = {"policy": row_policy.detach(), "value": row_value.detach(), "hit1": hit[:, 0].float(),
                "hit3": hit.any(dim=1).float()}
    return loss, metrics, rows


def mixed_loss(logits: torch.Tensor, value: torch.Tensor, batch: dict[str, Any], value_weight: float = 1.0,
               halves: bool = True) -> tuple[torch.Tensor, dict[str, torch.Tensor]]:
    """:func:`selfplay_loss` on a :func:`make_mixed_batch` batch (targets already on the model's device).

    The loss is the plain mean over all rows (self-play rows: masked cross-entropy against the visit
    distribution; human rows: unmasked cross-entropy against the stored move, as in stage 1). With
    ``halves`` the metrics add the per-half means ``policy_loss_self / value_loss_self / top1_self`` and
    ``..._human`` when the batch has both halves (a second, gradient-free pass over the logits: ask for it on
    the steps that are logged).
    """
    pi, z, mask = batch["pi"], batch["z"], batch.get("legal_mask")
    loss, metrics = selfplay_loss(logits, value, pi, z, mask, value_weight)
    n_self = int(batch.get("n_self", pi.shape[0]))
    n_human = int(batch.get("n_human", 0))
    if halves and n_self > 0 and n_human > 0:
        with torch.no_grad():
            rows = _row_losses(logits.detach(), value.detach(), pi, z, mask, value_weight)[2]
        for name, sl in (("self", slice(0, n_self)), ("human", slice(n_self, n_self + n_human))):
            metrics[f"policy_loss_{name}"] = rows["policy"][sl].mean()
            metrics[f"value_loss_{name}"] = rows["value"][sl].mean()
            metrics[f"top1_{name}"] = rows["hit1"][sl].mean()
    return loss, metrics


