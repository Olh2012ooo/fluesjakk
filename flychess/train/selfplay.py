class HumanStream:
    """An endless stream of ``batch``-sized batches from the imitation shards of ``cfg`` (SPEC §5 format).

    Uses ``load_split(cfg.shards_dir, cfg.val_fraction, cfg.seed, cfg.shard_name)`` (the training side, so
    the ``shard_name`` series and repeat factors apply exactly as in stage 1) and a shuffling
    :class:`ShardDataset`; the shard permutation changes every pass (``set_epoch``). Batches are the
    ``collate`` dicts (``planes float32 (B, 1280)``, ``move int64``, ``value float32``, ...).
    """

    def __init__(self, cfg: Any, batch: int, device: torch.device | None = None, seed: int = 0,
                 files: Sequence[str | Path] | None = None) -> None:
        if files is None:
            files, _ = load_split(str(_get(cfg, "shards_dir", "data/shards")), float(_get(cfg, "val_fraction", 0.02)),
                                  int(_get(cfg, "seed", 0)), _get(cfg, "shard_name", None))
        self.files = [Path(f) for f in files]
        if not self.files:
            raise FileNotFoundError("no imitation shards to mix into self-play training")
        self.batch = int(batch)
        self.epoch = 0
        self.positions = 0
        self.dataset = ShardDataset(self.files, seed=seed, shuffle=True)
        workers = min(int(_get(cfg, "num_workers", 0)), len(self.files), 2)
        kwargs: dict[str, Any] = {"prefetch_factor": 4} if workers > 0 else {}
        self.loader = DataLoader(self.dataset, batch_size=self.batch, collate_fn=collate, num_workers=workers,
                                 drop_last=True, pin_memory=device is not None and device.type == "cuda", **kwargs)
        self._it: Iterator[dict[str, torch.Tensor]] | None = None

    def next(self) -> dict[str, torch.Tensor]:
        """The next batch; a new pass (reshuffled) starts when the shards are exhausted."""
        for _ in range(2):
            if self._it is None:
                self.dataset.set_epoch(self.epoch)
                self._it = iter(self.loader)
            try:
                batch = next(self._it)
            except StopIteration:
                self._it = None
                self.epoch += 1
                continue
            self.positions += int(batch["move"].shape[0])
            return batch
        raise RuntimeError(f"the imitation shards yield no full batch of {self.batch} positions")

    __next__ = next

    def __iter__(self) -> HumanStream:
        return self


def human_targets(batch: dict[str, torch.Tensor]) -> dict[str, torch.Tensor]:
    """Self-play-style targets of a shard ``collate`` batch: one-hot ``pi`` on the stored move, an all-``True``
    ``legal_mask`` (stage 1 trains the *unmasked* softmax; the batch is treated the same way here) and ``z`` =
    the stored value (outcome or engine evaluation in [-1, 1])."""
    move = batch["move"].to(torch.int64).view(-1)
    B = move.shape[0]
    pi = torch.zeros(B, NUM_MOVES, dtype=torch.float32)
    pi[torch.arange(B), move] = 1.0
    return {"planes": batch["planes"].float(), "pi": pi, "z": batch["value"].float().view(-1),
            "legal_mask": torch.ones(B, NUM_MOVES, dtype=torch.bool)}


def make_mixed_batch(buffer: ReplayBuffer | None, human: HumanStream | None, batch_size: int, human_mix: float,
                     value_blend: float = 1.0, rng: np.random.Generator | None = None) -> dict[str, Any]:
    """One training batch: the first ``n_self`` rows are replay-buffer samples (``pi`` = visit distribution,
    ``z`` = blended value target, legal mask), the remaining ``round(batch_size · human_mix)`` rows come from
    the human stream (:func:`human_targets`). Returns ``{planes, pi, z, legal_mask, n_self, n_human}``."""
    batch_size = int(batch_size)
    n_human = round(batch_size * float(human_mix)) if human is not None else 0
    n_human = min(max(n_human, 0), batch_size)
    n_self = batch_size - n_human
    parts: list[dict[str, torch.Tensor]] = []
    if n_self > 0:
        if buffer is None or len(buffer) == 0:
            raise ValueError("replay buffer is empty")
        parts.append(buffer.sample(n_self, rng, value_blend=value_blend))
    if n_human > 0:
        hb = human.next()
        if int(hb["move"].shape[0]) != n_human:  # a stream built for another batch size
            raise ValueError(f"human stream yields batches of {int(hb['move'].shape[0])}, expected {n_human}")
        parts.append(human_targets(hb))
    keys = ("planes", "pi", "z", "legal_mask")
    out: dict[str, Any] = {k: torch.cat([p[k] for p in parts], dim=0) if len(parts) > 1 else parts[0][k] for k in keys}
    out["n_self"] = n_self
    out["n_human"] = n_human
    return out


