"""Stage 2 (v2): self-play generation, replay buffer, human-mixed training and gated promotion (SPEC §6).

Games are generated with :class:`~flychess.train.mcts.BatchedMCTS` — up to ``cfg.selfplay_lockstep_games``
games of an iteration are searched in lockstep so every simulation step is one GPU forward (more games
run as several lockstep batches) — with Dirichlet noise at the root, temperature 1 for the first
``cfg.temperature_plies`` plies and argmax afterwards, no resignation, and ``cfg.max_game_plies`` as a
hard cap (counted as a draw). The subtree below the chosen move is kept between plies. With
``cfg.selfplay_workers > 1`` the games are split across that many threads, each running its own
lockstep batches on the shared model: PyTorch releases the GIL inside the CUDA kernels, so one thread's
tree work overlaps the other threads' GPU time. **Games are always generated by the best network.**

Training targets per self-play position: quantised planes (exactly the shard format of SPEC §5), ``pi`` =
the root visit distribution, ``z`` = the game result from the mover's perspective and ``q`` = the root
search value; the value target is ``blend · z + (1 - blend) · q`` (``cfg.selfplay_value_blend``). Every
training batch is ``cfg.selfplay_human_mix`` positions streamed from the imitation shards (one-hot
policy target = the stored move, unmasked cross-entropy exactly like stage 1, value target = the stored
value) and the rest replay-buffer samples, so the human/engine knowledge is rehearsed instead of
forgotten (the v1 stage, trained on self-play targets only, made the searching player weaker).

Gating: after an iteration's training the candidate plays the current best weights with ``superfly``
(:class:`~flychess.play.engine.FlyEngine`, ``cfg.selfplay_gate_sims`` simulations) on paired distinct
openings, both colours; it is promoted to best only if its score fraction reaches
``cfg.selfplay_gate_threshold``, otherwise the weights *and* the AdamW moments revert to their pre-training
snapshot (the replay buffer is kept and the iteration counts). A gate that cannot run (the evaluator raises or
returns nothing) rejects the candidate the same way and stops the stage with ``RuntimeError`` — an untested
candidate is never promoted. ``runs/<run>/best.pt`` always holds the best network; ``latest.pt`` equals it
after gating. The openings of the gate match come from the iteration's own games; only when those yield too
few distinct positions is the list topped up from :func:`fixed_openings` (20 standard first moves — the one
place a move not chosen by the fly enters a match; ``fixed_openings_used`` on the elo record says how many). The replay buffer stores ``pi`` sparsely (top-``k`` visited moves) together with the legal-move
indices so that the policy loss can mask illegal moves like the search does.

The fly brain is the only thing choosing moves in these games.
"""
