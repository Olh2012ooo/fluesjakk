def _gpu_mem_gb(device: torch.device) -> float:
    if device.type == "cuda":
        return float(torch.cuda.max_memory_allocated(device)) / 1e9
    return 0.0


def _sample_activity(model: FlyBrain, board: chess.Board, device: torch.device, n: int = 2048
                     ) -> tuple[np.ndarray, np.ndarray]:
    x = torch.from_numpy(planes_from_features(board_features(board)[None]).reshape(1, -1)).to(device)
    with torch.no_grad():
        _, _, h = model(x, return_activity=True)
    h = h[0].float().cpu().numpy()
    idx = np.linspace(0, h.shape[0] - 1, num=min(n, h.shape[0]), dtype=np.int64)
    return idx, h[idx]


def completed_iterations(run_dir: str | Path, step: int) -> int:
    """Self-play iterations already finished at ``step`` according to the run's metrics.

    Every finished iteration writes a ``status`` record ``{stage: 'selfplay', iteration: n}``; the
    largest ``n`` at or before ``step`` is returned (0 when the run has no such record).
    """
    try:
        from flychess.train.metrics import read_metrics
    except ImportError:  # pragma: no cover
        return 0
    done = 0
    for rec in read_metrics(run_dir, kinds=["status"]):
        if rec.get("stage") == "selfplay" and rec.get("iteration") is not None and int(rec.get("step", -1)) <= step:
            done = max(done, int(rec["iteration"]))
    return done


def _resume_optim_state(run_dir: Path, step: int) -> dict | None:
    """The optimizer state of ``<run_dir>/latest.pt`` when it is a self-play checkpoint saved at ``step``."""
    latest = run_dir / "latest.pt"
    if not latest.exists():
        return None
    try:
        ck = torch.load(latest, map_location="cpu", weights_only=False)
    except Exception as e:  # noqa: BLE001 - a corrupt/foreign checkpoint must not stop the stage
        log.warning("could not read %s for the optimizer state: %r", latest, e)
        return None
    if ck.get("stage") == "selfplay" and int(ck.get("step", -1)) == int(step) and isinstance(ck.get("optim"), dict):
        return ck["optim"]
    return None


def _load_best(run_dir: Path, model: FlyBrain) -> int | None:
    """Load the weights of ``<run_dir>/best.pt`` into ``model``; returns the checkpoint's step, ``None`` if absent
    or unusable (a warning says why)."""
    path = run_dir / BEST
    if not path.exists():
        return None
    try:
        ck = torch.load(path, map_location="cpu", weights_only=False)
        model.load_state_dict(ck["model"])
    except Exception as e:  # noqa: BLE001 - a foreign / corrupt best.pt must not stop the stage
        warnings.warn(f"{path} could not be loaded ({e!r}): continuing with the weights of latest.pt", stacklevel=2)
        return None
    return int(ck.get("step", -1))


def _copy_optim_state(state: dict[str, Any]) -> dict[str, Any]:
    """A deep CPU copy of an optimizer ``state_dict`` (the AdamW moments and step counts) that no later
    ``optim.step()`` can change — the pre-training snapshot restored when a candidate is rejected."""
    moments = {k: {kk: (vv.detach().to("cpu", copy=True) if isinstance(vv, torch.Tensor) else copy.deepcopy(vv))
                   for kk, vv in v.items()} for k, v in state["state"].items()}
    return {"state": moments, "param_groups": copy.deepcopy(state["param_groups"])}


def _restore_optim(optim: torch.optim.Optimizer, snapshot: dict[str, Any] | None) -> None:
    """Put the optimizer back to ``snapshot`` (a :func:`_copy_optim_state`); a copy is loaded so the snapshot stays
    untouched by later steps."""
    if snapshot is not None:
        optim.load_state_dict(_copy_optim_state(snapshot))


def _save(save_checkpoint: Callable[..., Path], step: int, stage: str, optim: torch.optim.Optimizer) -> Path:
    """``save_checkpoint(step, stage, optim=...)`` when the callback accepts an optimizer, else without it."""
    try:
        params = inspect.signature(save_checkpoint).parameters
        takes_optim = "optim" in params or any(p.kind is inspect.Parameter.VAR_KEYWORD for p in params.values())
    except (TypeError, ValueError):
        takes_optim = False
    if takes_optim:
        return save_checkpoint(step, stage, optim=optim)
    return save_checkpoint(step, stage)


def _save_best(run_dir: Path, ckpt_path: Path | None) -> Path | None:
    """Copy the checkpoint just written (the best weights) to ``<run_dir>/best.pt`` (atomically)."""
    if ckpt_path is None or not Path(ckpt_path).is_file():
        return None
    run_dir.mkdir(parents=True, exist_ok=True)
    target = run_dir / BEST
    tmp = run_dir / f"{BEST}.tmp{os.getpid()}"
    shutil.copyfile(ckpt_path, tmp)
    os.replace(tmp, target)
    return target


class _Progress:
    """Counts the finished games of an iteration (thread-safe: ``selfplay_workers`` threads call it) and writes a
    progress line + ``status`` record (pos/s, ETA) every :data:`PROGRESS_GAMES` games and at the last one."""

    def __init__(self, logger: MetricsLogger, it: int, iters: int, total_games: int, step: int, total_steps: int) -> None:
        self.logger, self.it, self.iters, self.total_games = logger, it, iters, total_games
        self.step, self.total_steps = step, total_steps
        self.games = 0
        self.positions = 0
        self.t0 = time.time()
        self.lock = threading.Lock()

    def __call__(self, game: Game) -> None:
        with self.lock:
            self.games += 1
            self.positions += game.plies
            n, pos = self.games, self.positions
        if n % PROGRESS_GAMES == 0 or n == self.total_games:
            el = time.time() - self.t0
            rate = pos / max(el, 1e-9)
            log.info("selfplay iter %d: %d/%d games, %d positions in %.0fs (%.1f pos/s)", self.it, n, self.total_games,
                     pos, el, rate)
            self.logger.log_status(self.step, message=f"self-play iteration {self.it + 1}/{self.iters}: {n}/"
                                   f"{self.total_games} games ({rate:.0f} pos/s)", stage="selfplay",
                                   total_steps=self.total_steps, eta_s=el / n * (self.total_games - n))


@dataclass
class _TrainParams:
    """The static knobs of the training phase of an iteration (see :func:`_train_iteration`)."""

    steps: int
    batch_size: int
    human_mix: float
    value_blend: float
    value_weight: float
    grad_clip: float
    amp: bool
    log_every: int
    device: torch.device
    total_steps: int
    start_step: int


def _train_iteration(model: FlyBrain, optim: torch.optim.Optimizer, buffer: ReplayBuffer, human: HumanStream | None,
                     p: _TrainParams, rng: np.random.Generator, logger: MetricsLogger, step: int, it: int
                     ) -> tuple[int, dict[str, float]]:
    """``p.steps`` AdamW steps on mixed batches; returns ``(step, last metrics)``. Raises ``RuntimeError`` on a
    non-finite loss (before the model is updated with it)."""
    model.train()
    t_train = time.time()
    seen = 0
    last: dict[str, float] = {}
    try:
        for _ in range(p.steps):
            batch = make_mixed_batch(buffer, human, p.batch_size, p.human_mix, p.value_blend, rng)
            nb = p.device.type == "cuda"
            targets = {k: batch[k].to(p.device, non_blocking=nb) for k in ("planes", "pi", "z", "legal_mask")}
            targets["n_self"], targets["n_human"] = batch["n_self"], batch["n_human"]
            logged = (step + 1) % p.log_every == 0 or step + 1 in (p.start_step + 1, p.total_steps)
            with torch.autocast(device_type="cuda", dtype=torch.bfloat16, enabled=p.amp):
                logits, value = model(targets["planes"])[:2]
            loss, metrics = mixed_loss(logits, value, targets, p.value_weight, halves=logged)
            if not bool(torch.isfinite(loss)):
                logger.log_status(step, message=f"self-play loss is non-finite at step {step}: stopping",
                                  stage="selfplay", total_steps=p.total_steps, eta_s=None)
                raise RuntimeError(f"self-play loss became non-finite at step {step} (iteration {it}); "
                                   "the model was not updated with it — lower selfplay_lr or resume from the "
                                   "last checkpoint")
            optim.zero_grad(set_to_none=True)
            loss.backward()
            if p.grad_clip > 0:
                torch.nn.utils.clip_grad_norm_(model.parameters(), p.grad_clip)
            optim.step()
            step += 1
            seen += int(targets["planes"].shape[0])
            if logged:
                last = {k: float(v) for k, v in metrics.items()}
                elapsed = time.time() - t_train
                extra = {k: v for k, v in last.items() if k not in ("loss", "policy_loss", "value_loss", "top1", "top3")}
                logger.log_train(step, loss=last["loss"], policy_loss=last["policy_loss"], value_loss=last["value_loss"],
                                 top1=last["top1"], top3=last["top3"], lr=optim.param_groups[0]["lr"],
                                 pos_per_sec=seen / max(elapsed, 1e-9), gpu_mem_gb=_gpu_mem_gb(p.device),
                                 epoch=float(it), stage="selfplay", buffer=len(buffer), human_mix=p.human_mix,
                                 n_self=batch["n_self"], n_human=batch["n_human"], **extra)
    finally:
        model.eval()
    return step, last


def run_selfplay_stage(
    model: FlyBrain,
    graph: BrainGraph,
    cfg: Any,
    logger: MetricsLogger,
    start_step: int,
    save_checkpoint: Callable[[int, str], Path],
    device: str | torch.device | None = None,
    *,
    optim_state: dict | None = None,
    completed_iters: int | None = None,
) -> int:
    """Alternate self-play generation, mixed training and gating for ``cfg.selfplay_iters`` iterations; returns
    the final step.

    Each iteration (v2, SPEC §6):

    1. the **best** network generates ``cfg.selfplay_games_per_iter`` games (``cfg.mcts_sims`` simulations,
       lockstep batches of ``cfg.selfplay_lockstep_games``; a progress line / status record every 64 finished
       games) → replay buffer;
    2. ``cfg.selfplay_train_steps_per_iter`` AdamW steps (lr ``cfg.selfplay_lr``, batch
       ``cfg.selfplay_batch_size``) on mixed batches: ``cfg.selfplay_human_mix`` of every batch streams from
       the imitation shards (``cfg.shard_name`` series), the rest samples the buffer with the value target
       ``selfplay_value_blend · z + (1 - blend) · q``;
    3. gate (``cfg.selfplay_gate``): the candidate plays the best weights with ``superfly``
       (``cfg.selfplay_gate_games`` games, ``cfg.selfplay_gate_sims`` simulations, paired distinct openings
       from the iteration's games, topped up from :func:`fixed_openings`) and is promoted iff its score
       fraction ≥ ``cfg.selfplay_gate_threshold``; otherwise the weights and the optimizer moments revert to
       their pre-training snapshot (the replay buffer is kept, the iteration counts). An ``elo`` record with
       ``opponent='previous-best'`` (wins/draws/losses, score, threshold, promoted, openings,
       fixed_openings_used, truncated, mean_plies) is logged. A gate that cannot run (the evaluator raises or
       returns nothing) rejects the candidate the same way, logs a ``status`` record with ``gate_error`` and
       raises ``RuntimeError`` — the untested candidate is never promoted;
    4. every ``cfg.selfplay_eval_every_iters`` iterations (and after the last) ``cfg.elo_games`` games as ``fly``
       against a random opponent (``opponent='random'``; without the gate also ``'previous-iteration'``);
    5. ``save_checkpoint(step, 'selfplay')`` (with ``optim=`` when the callback accepts it) → ``ckpt-<step>.pt``
       and ``latest.pt`` hold the best weights, which are also copied to ``best.pt``; a status record with
       ``iteration`` and ``promoted`` marks the iteration as done.

    Resuming: ``completed_iters`` defaults to what the run's metrics say (see :func:`completed_iterations`)
    and ``optim_state`` to the optimizer state of ``<run_dir>/latest.pt`` when that checkpoint was saved by
    this stage at ``start_step``; iterations already done are skipped and ``best.pt`` (when present after at
    least one finished iteration) is loaded as the best network; ``cfg.selfplay_lr`` / the betas / the weight
    decay of the config win over the restored optimizer's. A ``RuntimeError`` (a non-finite loss, a gate that
    could not run) and ``KeyboardInterrupt`` both restore the best weights, save ``latest.pt`` / ``best.pt`` and
    are re-raised.
    """
    device = torch.device(device) if device is not None else next(model.parameters()).device
    iters = int(_get(cfg, "selfplay_iters", 50))
    games_per_iter = int(_get(cfg, "selfplay_games_per_iter", 512))
    sims = int(_get(cfg, "mcts_sims", 100))
    steps_per_iter = int(_get(cfg, "selfplay_train_steps_per_iter", 400))
    batch_size = int(_get(cfg, "selfplay_batch_size", 384))
    human_mix = float(_get(cfg, "selfplay_human_mix", 0.5))
    value_blend = float(_get(cfg, "selfplay_value_blend", 0.5))
    gate = bool(_get(cfg, "selfplay_gate", True))
    gate_games = int(_get(cfg, "selfplay_gate_games", 40))
    gate_sims = int(_get(cfg, "selfplay_gate_sims", 100))
    gate_threshold = float(_get(cfg, "selfplay_gate_threshold", 0.55))
    value_weight = float(_get(cfg, "value_loss_weight", 1.0))
    grad_clip = float(_get(cfg, "grad_clip", 1.0))
    amp = bool(_get(cfg, "amp", True)) and device.type == "cuda"
    log_every = max(1, int(_get(cfg, "log_every", 20)))
    elo_games = int(_get(cfg, "elo_games", 20))
    eval_every_iters = max(1, int(_get(cfg, "selfplay_eval_every_iters", 5) or 5))
    seed = int(_get(cfg, "seed", 0))
    rng = np.random.default_rng(seed + 12345)
    run_dir = Path(getattr(logger, "run_dir", "."))
    if not (0.0 <= human_mix <= 1.0) or not (0.0 <= value_blend <= 1.0):
        raise ValueError("selfplay_human_mix and selfplay_value_blend must lie in [0, 1]")
    gate = gate and gate_games > 0

    if completed_iters is None:
        completed_iters = completed_iterations(run_dir, start_step) if start_step > 0 else 0
    completed_iters = max(0, min(int(completed_iters), iters))
    if optim_state is None and start_step > 0:
        optim_state = _resume_optim_state(run_dir, start_step)

    buffer = ReplayBuffer(int(_get(cfg, "replay_buffer_size", 200_000)), k=max(64, sims), seed=seed + completed_iters)
    weight_decay = float(_get(cfg, "weight_decay", 1e-4))
    groups = param_groups(model, weight_decay)  # same decay rule as imitation: no decay on gains / biases
    lr = float(_get(cfg, "selfplay_lr", 1e-4))
    optim = torch.optim.AdamW(groups, lr=lr, betas=ADAM_BETAS, weight_decay=weight_decay)  # betas as in imitation
    if optim_state is not None:
        try:
            optim.load_state_dict(adapt_optim_state(optim_state, model, weight_decay, groups))
        except (ValueError, KeyError, RuntimeError) as e:
            log.warning("could not restore the self-play optimizer state (%r): starting it fresh", e)
        else:
            for g, fresh in zip(optim.param_groups, groups, strict=True):
                # the checkpoint's hyper-parameters must not win over cfg (the lr is constant here, so unlike
                # imitation nothing re-sets it per step: a changed selfplay_lr on --resume applies from here)
                g["weight_decay"] = fresh["weight_decay"]
                g["lr"] = lr
                g["betas"] = ADAM_BETAS
    step = int(start_step)
    total_steps = start_step + (iters - completed_iters) * steps_per_iter
    t_stage = time.time()
    best_state: dict[str, torch.Tensor] | None = None   # set while the model holds an ungated candidate
    optim_snapshot: dict[str, Any] | None = None         # the optimizer state that goes with best_state
    if completed_iters >= iters:
        logger.log_status(step, message=f"self-play stage already finished ({completed_iters}/{iters} iterations)",
                          stage="selfplay", total_steps=total_steps, eta_s=0.0)
        return step
    resumed_best = _load_best(run_dir, model) if completed_iters > 0 else None
    if resumed_best is not None:
        log.info("resumed the best network from %s (step %d)", run_dir / BEST, resumed_best)
    logger.log_status(step, message=("self-play stage starting" if completed_iters == 0 else
                                     f"self-play stage resuming after iteration {completed_iters}/{iters}"),
                      stage="selfplay", total_steps=total_steps, eta_s=None,
                      **({"best_loaded_step": resumed_best} if resumed_best is not None else {}))

    human: HumanStream | None = None
    n_human = round(batch_size * human_mix)
    if n_human > 0:
        human = HumanStream(cfg, n_human, device, seed=seed + 777 + completed_iters)
        log.info("human mix: %d of every %d training positions stream from %d imitation shard file(s)",
                 n_human, batch_size, len(human.files))
    params = _TrainParams(steps=steps_per_iter, batch_size=batch_size, human_mix=human_mix, value_blend=value_blend,
                          value_weight=value_weight, grad_clip=grad_clip, amp=amp, log_every=log_every, device=device,
                          total_steps=total_steps, start_step=start_step)

    try:
        for it in range(completed_iters, iters):
            # ---- 1. generate games with the best network ------------------------------------------
            t0 = time.time()
            on_game = _Progress(logger, it, iters, games_per_iter, step, total_steps)
            games = generate_games(model, graph, cfg, games_per_iter, device, rng, on_game=on_game, sims=sims)
            gen_s = time.time() - t0
            positions = sum(g.plies for g in games)
            for g in games:
                buffer.add(g)
            lengths = np.array([g.plies for g in games], dtype=np.float64)
            results = {"1-0": 0, "0-1": 0, "1/2-1/2": 0}
            for g in games:
                results[g.result] += 1
            capped = sum(g.capped for g in games)
            log.info("selfplay iter %d: %d games, %d positions in %.1fs (%.1f pos/s), plies mean %.1f, %s, capped %d",
                     it, len(games), positions, gen_s, positions / max(gen_s, 1e-9), lengths.mean() if len(lengths) else 0,
                     results, capped)
            logger.log("selfplay", step, iteration=it, games=len(games), positions=positions, gen_seconds=gen_s,
                       pos_per_sec=positions / max(gen_s, 1e-9), plies_mean=float(lengths.mean()) if len(lengths) else 0.0,
                       plies_min=int(lengths.min()) if len(lengths) else 0, plies_max=int(lengths.max()) if len(lengths) else 0,
                       white_wins=results["1-0"], black_wins=results["0-1"], draws=results["1/2-1/2"], capped=capped,
                       buffer=len(buffer), sims=sims)
            sample = max(games, key=lambda g: (not g.capped, g.plies), default=None)
            if sample is not None:
                logger.log_game(step, pgn=sample.pgn, result=sample.result, moves=(sample.plies + 1) // 2, source="selfplay")
            if games:
                board = chess.Board()
                for uci in sample.moves[: min(len(sample.moves), 20)]:
                    board.push_uci(uci)
                idx, vals = _sample_activity(model, board, device)
                logger.log_activity(step, neuron_idx=idx, values=vals)

            # ---- 2. train the candidate on mixed batches --------------------------------------------
            best_state = {k: v.detach().to("cpu", copy=True) for k, v in model.state_dict().items()}
            optim_snapshot = _copy_optim_state(optim.state_dict())
            t_train = time.time()
            step, last = _train_iteration(model, optim, buffer, human, params, rng, logger, step, it)
            train_s = time.time() - t_train
            done_iters = it + 1

            # ---- 3. gate: candidate vs best with superfly ------------------------------------------
            promoted = True
            gated = False
            if gate:
                openings, n_fixed = _match_openings(games, (gate_games + 1) // 2, rng)
                start_fens = paired_start_fens(openings, gate_games)
                t_gate = time.time()
                gate_error: str | None = None
                try:
                    out = gate_candidate(model, best_state, graph, cfg, device, gate_games, gate_sims, gate_threshold,
                                         start_fens, seed + 1000 + done_iters)
                except Exception as e:  # noqa: BLE001 - whatever broke the evaluator, the candidate is untested
                    out, gate_error = None, repr(e)
                if out is None:
                    # An untested candidate is never promoted: revert to best (weights + optimizer moments), record
                    # why and stop — the operator must fix the gate (SPEC §6); --resume redoes this iteration.
                    gate_error = gate_error or "the gate match could not be played (FlyEngine unavailable or an unexpected match result)"
                    model.load_state_dict(best_state)
                    _restore_optim(optim, optim_snapshot)
                    model.eval()
                    log.error("selfplay iter %d: the gate could not run (%s): candidate rejected, stopping", it, gate_error)
                    logger.log_status(step, message=f"self-play iteration {done_iters}/{iters}: gate could not run "
                                      f"({gate_error}); candidate rejected, weights revert to best, stopping",
                                      stage="selfplay", total_steps=total_steps, eta_s=None, promoted=False, gated=False,
                                      gate_error=gate_error)
                    raise RuntimeError(f"self-play gate could not run in iteration {done_iters} ({gate_error}); the "
                                       "candidate was rejected and the best weights saved — fix the evaluator and "
                                       "resume")
                gated = True
                promoted = bool(out["promoted"])
                logger.log_elo(step, opponent=GATE_OPPONENT, games=int(out["games"]), wins=int(out["wins"]),
                               draws=int(out["draws"]), losses=int(out["losses"]),
                               elo_estimate=float(out["elo_estimate"]), score=float(out["score"]),
                               threshold=gate_threshold, promoted=promoted, openings=int(out.get("openings", 1)),
                               fixed_openings_used=int(n_fixed), truncated=int(out.get("truncated", 0)),
                               mean_plies=float(out.get("mean_plies", 0.0)), sims=gate_sims, iteration=done_iters,
                               seconds=time.time() - t_gate, stage="selfplay")
                verdict = (f"candidate promoted (score {out['score']:.3f} >= {gate_threshold:.2f})" if promoted else
                           f"candidate rejected (score {out['score']:.3f} < {gate_threshold:.2f}), weights revert to best")
                log.info("selfplay iter %d gate vs %s: +%d =%d -%d (%d openings, %d fixed, %d truncated, %d sims, "
                         "Elo %+.0f): %s", it, GATE_OPPONENT, out["wins"], out["draws"], out["losses"],
                         out.get("openings", 1), n_fixed, out.get("truncated", 0), gate_sims, out["elo_estimate"], verdict)
                logger.log_status(step, message=f"self-play iteration {done_iters}/{iters}: {verdict} "
                                  f"(+{out['wins']} ={out['draws']} -{out['losses']} vs {GATE_OPPONENT})",
                                  stage="selfplay", total_steps=total_steps, eta_s=None)
                pgns = out.get("pgns") or ([out["pgn"]] if out.get("pgn") else [])
                if pgns:  # the gate game is the most informative sample: not subject to the per-minute limit
                    logger.log_game(step, pgn=pgns[0], result=_pgn_result(pgns[0]), moves=_pgn_moves(pgns[0]),
                                    source="eval", opponent=GATE_OPPONENT, force=True)
                if not promoted:
                    model.load_state_dict(best_state)
                    _restore_optim(optim, optim_snapshot)   # the moments of a rejected direction go with it
            prev_state = best_state          # the weights the iteration started from (for 'previous-iteration')
            best_state = None                # the model holds the best network again
            optim_snapshot = None
            model.eval()

            # ---- 4. periodic evaluation: vs a random opponent (and vs the previous iteration without a gate) ----
            if elo_games > 0 and (done_iters % eval_every_iters == 0 or done_iters == iters):
                openings = match_openings(games, (elo_games + 1) // 2, rng)
                start_fens = paired_start_fens(openings, elo_games)
                opponents = ["random"] if gated else ["previous-iteration", "random"]
                for opponent in opponents:
                    try:
                        if opponent == "previous-iteration":
                            out = _evaluate_vs_previous(model, prev_state, graph, cfg, device, elo_games,
                                                        start_fens, seed + done_iters)
                        else:
                            out = _evaluate_vs_random(model, graph, cfg, device, elo_games, start_fens,
                                                      seed + done_iters)
                    except Exception as e:  # noqa: BLE001 - evaluation must never kill training
                        warnings.warn(f"evaluation vs {opponent} failed: {e!r}", stacklevel=2)
                        out = None
                    if out is None:
                        continue
                    logger.log_elo(step, opponent=opponent, games=int(out["games"]), wins=int(out["wins"]),
                                   draws=int(out["draws"]), losses=int(out["losses"]),
                                   elo_estimate=float(out["elo_estimate"]), openings=int(out.get("openings", 1)),
                                   iteration=done_iters)
                    log.info("selfplay iter %d vs %s: +%d =%d -%d (%d openings, Elo %+.0f)", it, opponent,
                             out["wins"], out["draws"], out["losses"], out.get("openings", 1), out["elo_estimate"])
                    pgns = out.get("pgns") or ([out["pgn"]] if out.get("pgn") else [])
                    if pgns:  # a sample evaluation game for the dashboard (rate limited by the logger)
                        logger.log_game(step, pgn=pgns[0], result=_pgn_result(pgns[0]), moves=_pgn_moves(pgns[0]),
                                        source="eval", opponent=opponent)

            # ---- 5. checkpoint (= best) + best.pt + status ---------------------------------------------
            ckpt_path = _save(save_checkpoint, step, "selfplay", optim)
            _save_best(run_dir, ckpt_path)
            eta = (time.time() - t_stage) / (done_iters - completed_iters) * (iters - done_iters)
            logger.log_status(step, message=f"self-play iteration {done_iters}/{iters} done "
                              f"({'promoted' if promoted else 'rejected'}; {len(games)} games in {gen_s:.0f}s, "
                              f"{steps_per_iter} steps in {train_s:.0f}s"
                              + (f", loss {last['loss']:.3f}" if last else "") + ")",
                              stage="selfplay", total_steps=total_steps, eta_s=eta, iteration=done_iters,
                              promoted=promoted, gated=gated)

    except KeyboardInterrupt:
        if best_state is not None:  # interrupted while the model held an ungated candidate: latest.pt = best
            model.load_state_dict(best_state)
            model.eval()
        log.warning("interrupted: saving self-play checkpoint (best weights) at step %d", step)
        _save_best(run_dir, _save(save_checkpoint, step, "selfplay", optim))
        logger.log_status(step, message="self-play interrupted (checkpoint saved)", stage="selfplay",
                          total_steps=total_steps, eta_s=None)
        raise
    except RuntimeError:
        if best_state is not None:  # the model held an ungated candidate (non-finite loss, a failed gate): revert
            model.load_state_dict(best_state)
            _restore_optim(optim, optim_snapshot)
            model.eval()
        log.warning("self-play stopped by an error: saving checkpoint (best weights) at step %d", step)
        _save_best(run_dir, _save(save_checkpoint, step, "selfplay", optim))
        raise
    logger.log_status(step, message="self-play stage finished", stage="selfplay", total_steps=total_steps, eta_s=0.0)
    return step


def _pgn_result(pgn: str) -> str:
    for token in ("1-0", "0-1", "1/2-1/2"):
        if f'[Result "{token}"]' in pgn:
            return token
    return "*"


def _pgn_moves(pgn: str) -> int:
    """Full moves in a PGN string (0 if it does not parse)."""
    game = chess.pgn.read_game(io.StringIO(pgn))
    if game is None:
        return 0
    plies = sum(1 for _ in game.mainline_moves())
    return (plies + 1) // 2


